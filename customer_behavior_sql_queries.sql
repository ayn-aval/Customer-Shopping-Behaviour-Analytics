-- Q11. Seasonal revenue trends — which season drives the most sales
--      per category?
WITH seasonal_sales AS (
    SELECT p.category,
           o.season,
           ROUND(SUM(o.purchase_amount), 2)  AS total_revenue,
           COUNT(o.order_id)                 AS total_orders,
           DENSE_RANK() OVER (
               PARTITION BY p.category
               ORDER BY SUM(o.purchase_amount) DESC
           ) AS season_rank
    FROM products p
    JOIN orders o ON p.product_id = o.product_id
    GROUP BY p.category, o.season
)
SELECT category, season, total_revenue, total_orders, season_rank
FROM seasonal_sales
WHERE season_rank = 1
ORDER BY total_revenue DESC;


-- Q12. Cumulative revenue by age group — running total analysis.
WITH age_revenue AS (
    SELECT
        CASE
            WHEN c.age < 25             THEN '18-24'
            WHEN c.age BETWEEN 25 AND 34 THEN '25-34'
            WHEN c.age BETWEEN 35 AND 44 THEN '35-44'
            WHEN c.age BETWEEN 45 AND 54 THEN '45-54'
            ELSE '55+'
        END AS age_group,
        ROUND(SUM(o.purchase_amount), 2) AS total_revenue
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY age_group
)
SELECT age_group,
       total_revenue,
       SUM(total_revenue) OVER (ORDER BY total_revenue DESC) AS cumulative_revenue,
       ROUND(
           100.0 * SUM(total_revenue) OVER (ORDER BY total_revenue DESC)
           / SUM(total_revenue) OVER (), 2
       ) AS cumulative_pct
FROM age_revenue
ORDER BY total_revenue DESC;


-- Q13. Top 25% high-value customers using NTILE quartile analysis.
WITH customer_spend AS (
    SELECT c.customer_id,
           c.gender,
           c.location,
           c.subscription_status,
           ROUND(AVG(o.purchase_amount), 2) AS avg_spend,
           COUNT(o.order_id)                AS total_orders,
           NTILE(4) OVER (ORDER BY AVG(o.purchase_amount) DESC) AS spend_quartile
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.gender, c.location, c.subscription_status
)
SELECT customer_id, gender, location, subscription_status,
       avg_spend, total_orders
FROM customer_spend
WHERE spend_quartile = 1
ORDER BY avg_spend DESC
LIMIT 20;


-- Q14. Payment method preference by gender — cross-tabulation with
--      percentage breakdown within each gender.
SELECT c.gender,
       c.payment_method,
       COUNT(o.order_id)                     AS total_orders,
       ROUND(SUM(o.purchase_amount), 2)      AS total_revenue,
       ROUND(AVG(o.purchase_amount), 2)      AS avg_order_value,
       COALESCE(
           ROUND(
               100.0 * COUNT(o.order_id)
               / NULLIF(SUM(COUNT(o.order_id)) OVER (PARTITION BY c.gender), 0), 2
           ), 0
       ) AS pct_within_gender
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.gender, c.payment_method
ORDER BY c.gender, total_orders DESC;


-- Q15. Top 10 locations by revenue with customer count and avg rating.
SELECT c.location,
       COUNT(DISTINCT c.customer_id)           AS unique_customers,
       COUNT(o.order_id)                       AS total_orders,
       ROUND(SUM(o.purchase_amount), 2)        AS total_revenue,
       ROUND(AVG(o.purchase_amount), 2)        AS avg_order_value,
       ROUND(AVG(o.review_rating::NUMERIC), 2) AS avg_rating
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.location
HAVING COUNT(o.order_id) >= 5
ORDER BY total_revenue DESC
LIMIT 10;
